"""Write data/DATASHEET.md from the data files (counts are never typed by hand).

    uv run --project duel python scripts/datasheet.py
"""

from __future__ import annotations

import json
from collections import Counter

from _common import DATA
from genlingo_duel.dataset import load_pairs, read_jsonl

COUNTRY_ORDER = ["MX", "GT", "CO", "LATAM"]


def table(head: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def crosstab(pairs, row_key, col_key, cols) -> str:
    c = Counter((row_key(p), col_key(p)) for p in pairs)
    rows = sorted({row_key(p) for p in pairs})
    body = [[r, *[c[(r, k)] for k in cols], sum(c[(r, k)] for k in cols)] for r in rows]
    body.append(["**total**", *[sum(c[(r, k)] for r in rows) for k in cols], len(pairs)])
    return table(["", *cols, "total"], body)


def main() -> None:
    pairs = load_pairs(DATA)
    terms = list(read_jsonl(DATA / "terms.jsonl"))
    usage = list(read_jsonl(DATA / "raw" / "web_usage.jsonl"))
    meta_path = DATA / "pairs" / "synthetic.meta.json"
    meta = json.loads(meta_path.read_text()) if meta_path.exists() else {}
    sources = sum(1 for line in (DATA / "SOURCES.md").read_text().splitlines() if line.startswith("| S"))

    split_origin = lambda p: f"{p.split} · {p.origin}"  # noqa: E731
    term_tab = Counter((t["country"], t["generation"]) for t in terms)
    usage_tab = Counter((u["country"], u.get("example_origin", "source")) for u in usage)

    md = f"""# Datasheet — Genlingo pairs

Generated by `scripts/datasheet.py` from the files in `data/`. Do not edit the numbers by hand.

## Motivation

Genlingo fine-tunes a small Gemma model ("David") to translate between Gen Z Spanish and the
speech of their parents, in both directions, for four variants: Mexico (MX), Guatemala (GT),
Colombia (CO) and neutral Latin American Spanish (LATAM). The dataset exists to show that a
small model trained on **its own, well-documented data** can compete with a frontier model on a
narrow task — and to evaluate that claim honestly.

## Composition

Each record is a pair: `id`, `direction` (`genz_to_parent` | `parent_to_genz`), `source`,
`target`, `country`, `age_range`, `split` (`train` | `test`), `status`
(`pending_review` | `approved` | `rejected`), `origin` (`web` | `synthetic` | `human`) and
`provenance`.

- `age_range` is the age range of the Gen Z side (16-24 by default; audience pairs carry the
  contributor's self-reported range). Web pairs also record `speaker_age_range` of the source
  sentence in their provenance.

### Pairs by split and origin × direction

{crosstab(pairs, split_origin, lambda p: p.direction, ["genz_to_parent", "parent_to_genz"])}

### Pairs by split and origin × country

{crosstab(pairs, split_origin, lambda p: p.country, COUNTRY_ORDER)}

### Pairs by split and origin × status

{crosstab(pairs, split_origin, lambda p: p.status, ["approved", "pending_review", "rejected"])}

### Term bank (`data/terms.jsonl`)

{len(terms)} terms from {sources} sources (see `SOURCES.md`).

{table(["country", "genz", "parent", "total"], [[c, term_tab[(c, "genz")], term_tab[(c, "parent")], term_tab[(c, "genz")] + term_tab[(c, "parent")]] for c in COUNTRY_ORDER])}

### Web usage examples (`data/raw/web_usage.jsonl`, source of the test set)

{table(["country", "verbatim from source", "curator-written", "total"], [[c, usage_tab[(c, "source")], usage_tab[(c, "curator")], usage_tab[(c, "source")] + usage_tab[(c, "curator")]] for c in COUNTRY_ORDER])}

## Collection process

1. **Web research** (`origin=web`). Glossaries, dictionaries (Wiktionary, Diccionario de
   americanismos), news and magazine articles explaining Gen Z slang and older colloquial
   speech. Only facts (a term and what it means) and short, attributed usage examples are
   taken. Every source, its owner and its terms are listed in `SOURCES.md`.
2. **Term bank.** One line per term: meaning (paraphrased), country, generation, one example,
   source URL.
3. **Synthetic training pairs** (`origin=synthetic`, `split=train` only). Generated by
   `scripts/generate_pairs.py` with `{meta.get("model", "GEMINI_MODEL")}` (prompt
   `{meta.get("prompt_version", "?")}`, base seed `{meta.get("base_seed", "?")}`), anchored on one real
   term per call (term, meaning, example, country). Each pair records model, prompt version and
   seed. Automatic checks drop pairs that fail the schema, are too long, identical on both
   sides, duplicated, or overlap a test sentence. Last run: {meta.get("kept", 0)} kept of
   {meta.get("generated", 0)} generated (dropped: {meta.get("dropped", {})}), cost
   ≈ ${meta.get("cost_usd", 0)} in {meta.get("duration_s", "?")} s.
4. **Test pairs** (`origin=web`, `split=test`). The source is a real sentence from the web; the
   reference is the curator's rewrite into the other generation's speech, based on the meaning
   the source gives. **Never synthetic:** a reference written by Gemini would bias chrF++ toward
   Gemini (Goliath). Every test pair starts as `pending_review`; the presenter approves or
   corrects it with `make review-test`.
5. **Audience pairs** (`origin=human`). Submitted at each event from the audience app, approved
   by the presenter in `/admin`, pulled with `make export`. 20% go to the test split (stable
   hash of the id).

## Uses

Training David (`split=train`, `status=approved`), duel evaluation rounds and `make eval`
(`split=test`, `status=approved`; `pending_review` only in rehearsal reports, labelled as such).

## Known limitations

- Guatemalan Gen Z slang is thinly documented online; GT has fewer terms and test pairs.
- Slang ages fast: a term bank dated today will sound old in a year. Models are tagged by data
  date (`genlingo-YYYY-MM`) so the talk can compare last month's David with this month's.
- Test references are one person's rewrite; chrF++ against a single reference underestimates
  valid alternative translations. Results are reported per origin and per direction.
"""
    (DATA / "DATASHEET.md").write_text(md, encoding="utf-8")
    print(f"DATASHEET.md: {len(pairs)} pairs, {len(terms)} terms")


if __name__ == "__main__":
    main()
