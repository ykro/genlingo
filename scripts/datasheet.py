"""Write data/DATASHEET.md from the data files (counts are never typed by hand).

    uv run --project duel python scripts/datasheet.py
"""

from __future__ import annotations

import json
from collections import Counter

from _common import DATA
from genlingo_duel.dataset import load_pairs, read_jsonl

COUNTRY_ORDER = ["MX", "GT", "CO", "LATAM"]


def table(head: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def crosstab(pairs, row_key, col_key, cols) -> str:
    c = Counter((row_key(p), col_key(p)) for p in pairs)
    rows = sorted({row_key(p) for p in pairs})
    body = [[r, *[c[(r, k)] for k in cols], sum(c[(r, k)] for k in cols)] for r in rows]
    body.append(["**total**", *[sum(c[(r, k)] for r in rows) for k in cols], len(pairs)])
    return table(["", *cols, "total"], body)


def main() -> None:
    pairs = load_pairs(DATA)
    terms = list(read_jsonl(DATA / "terms.jsonl"))
    usage = list(read_jsonl(DATA / "raw" / "web_usage.jsonl"))
    meta_path = DATA / "pairs" / "synthetic.meta.json"
    meta = json.loads(meta_path.read_text()) if meta_path.exists() else {}
    # Sources the data actually uses (terms + real sentences of both rounds); SOURCES.md also lists
    # S63, a general-speech corpus used only to count ambiguous terms.
    used = {r.get("source_id") for f in ("terms.jsonl", "raw/web_usage.jsonl", "raw/web_usage_v2.jsonl")
            for r in read_jsonl(DATA / f)} - {None}
    sources = len(used)

    split_origin = lambda p: f"{p.split} · {p.origin}"  # noqa: E731
    rf = meta.get("refiltered")
    refilter_text = (f"Re-validated against the grown term bank ({rf['terms']} terms): {rf['kept']} kept, dropped "
                     + ", ".join(f"{k} {v}" for k, v in rf["dropped"].items()) + ".") if rf else ""
    kinds_text = ", ".join(f"`{k}` {v}" for k, v in sorted(meta.get("kinds", {}).items())) or "—"
    dropped_text = ", ".join(f"{k} {v}" for k, v in sorted(meta.get("dropped", {}).items(), key=lambda kv: -kv[1])) or "—"
    term_tab = Counter((t["country"], t["generation"]) for t in terms)
    usage_tab = Counter((u["country"], u.get("example_origin", "source")) for u in usage)

    md = f"""# Datasheet — Genlingo pairs

Generated by `scripts/datasheet.py` from the files in `data/`. Do not edit the numbers by hand.

## Motivation

Genlingo fine-tunes a small Gemma model ("David") to translate between Gen Z Spanish and the
speech of their parents, in both directions, for four variants: Mexico (MX), Guatemala (GT),
Colombia (CO) and neutral Latin American Spanish (LATAM). The dataset exists to show that a
small model trained on **its own, well-documented data** can compete with a frontier model on a
narrow task — and to evaluate that claim honestly.

## Composition

Each record is a pair: `id`, `direction` (`genz_to_parent` | `parent_to_genz`), `source`,
`target`, `country`, `age_range`, `split` (`train` | `test`), `status`
(`pending_review` | `auto_validated` | `approved` | `rejected`), `origin` (`web` | `synthetic` | `human`) and
`provenance`.

- `age_range` is the age range of the Gen Z side (16-24 by default; audience pairs carry the
  contributor's self-reported range). Web pairs also record `speaker_age_range` of the source
  sentence in their provenance.

### Pairs by split and origin × direction

{crosstab(pairs, split_origin, lambda p: p.direction, ["genz_to_parent", "parent_to_genz"])}

### Pairs by split and origin × country

{crosstab(pairs, split_origin, lambda p: p.country, COUNTRY_ORDER)}

### Pairs by split and origin × status

{crosstab(pairs, split_origin, lambda p: p.status, ["auto_validated", "approved", "pending_review", "rejected"])}

### Term bank (`data/terms.jsonl`)

{len(terms)} terms from {sources} web sources (see `SOURCES.md`; S63 there is a general-speech corpus used only to
count ambiguous terms, not a source of terms or sentences).

{table(["country", "genz", "parent", "total"], [[c, term_tab[(c, "genz")], term_tab[(c, "parent")], term_tab[(c, "genz")] + term_tab[(c, "parent")]] for c in COUNTRY_ORDER])}

### Web usage examples (`data/raw/web_usage.jsonl`, source of the test set)

{table(["country", "verbatim from source", "curator-written", "total"], [[c, usage_tab[(c, "source")], usage_tab[(c, "curator")], usage_tab[(c, "source")] + usage_tab[(c, "curator")]] for c in COUNTRY_ORDER])}

## Collection process

1. **Web research** (`origin=web`). Glossaries, dictionaries (Wiktionary, Diccionario de
   americanismos), news and magazine articles explaining Gen Z slang and older colloquial
   speech. Only facts (a term and what it means) and short, attributed usage examples are
   taken. Every source, its owner and its terms are listed in `SOURCES.md`.
2. **Term bank.** One line per term: meaning (paraphrased), country, generation, one example,
   source URL.
3. **Synthetic training pairs** (`origin=synthetic`, `split=train` only), `{meta.get("prompt_version", "?")}`.
   Generated by `scripts/generate_pairs.py` with `{meta.get("model", "GEMINI_MODEL")}` (base seed
   `{meta.get("base_seed", "?")}`). Every pair is a **term substitution built from the term bank**: each
   call names the slang term and its counterpart in the other generation, both from the pair's country
   (counterparts found with `{meta.get("embedding_model", "?")}` over the term meanings). Pair kinds:
   {kinds_text}. `p2g_trap` pairs are **hard negatives**: they name a similar term from another country
   that must *not* appear ("in Mexico it's «feria», not «pisto»").
   Rebalanced toward papás → Gen Z (60 / 40), the direction the previous David was worst at.
   **Validation against the term bank** (every pair): the expected term is in the source/target, no
   term from another country, Gen Z → papás targets carry no Gen Z slang, papás → Gen Z targets carry
   Gen Z slang of the country and replace the parents' expression. Plus schema, length, duplicates and
   test-set leakage. Last run: {meta.get("generated", 0)} generated, {meta.get("valid", 0)} valid,
   {meta.get("kept", 0)} kept after rebalancing; rejected by reason: {dropped_text}. Cost
   ≈ ${meta.get("cost_usd", 0)} in {meta.get("duration_s", "?")} s.
   {refilter_text}
   History: `pairs-v1` (free paraphrase) and `pairs-v2` (minimal edits) are in git history; their
   Davids are kept as `train/runs/experiments/` and `genlingo-2026-09`.
4. **Test pairs** (`origin=web`, `split=test`). The source is a real sentence from the web; the
   reference is the curator's rewrite into the other generation's speech, based on the meaning
   the source gives. **Never synthetic:** a reference written by Gemini would bias chrF++ toward
   Gemini (Goliath). Every candidate is **validated automatically against the term bank**
   (`scripts/validate_test_set.py`, no human needed): Gen Z → papás sources must contain a Gen Z
   term of their country and the reference must replace it; papás → Gen Z references must contain
   Gen Z slang of the country; no other-country terms; sane length; no overlap with training.
   Passing pairs are `auto_validated`, failing ones `rejected` with the reason. A human pass
   (`make review-test`) is optional and overrides the automatic decision.
5. **Real-anchored training pairs** (`origin=web`, `split=train`, `data/pairs/real_train.jsonl`). A second
   research round (`data/raw/web_usage_v2.jsonl`, sources S41+) is split by a stable hash of the id:
   half becomes test pairs, half becomes training pairs built from the **real sentence** and the
   curator's rewrite, in both directions (real -> rewrite and rewrite -> real, so papás -> Gen Z also
   learns to produce real Gen Z speech). Same automatic term-bank checks as the test set; a sentence is
   never in both splits.
6. **Ambiguous terms.** Some term-bank entries are also ordinary words ("cámara", "servir", "alta").
   `scripts/flag_ambiguous_terms.py` counts their matches in ~39k sentences of general speech
   (transcripts; only counts are kept, no text) and marks the ones with ≥ 15 matches
   `ambiguous: true`; metrics and test validation ignore them, the glossary still explains them.
7. **Audience pairs** (`origin=human`). Submitted at each event from the audience app, approved
   by the presenter in `/admin`, pulled with `make export`. 20% go to the test split (stable
   hash of the id).

## Uses

Training David (`split=train`, status `auto_validated` or `approved`), duel evaluation rounds and
`make eval` (`split=test`, status `auto_validated`: validated automatically, no human needed; a
human pass with `make review-test` is optional and its `approved`/`rejected` decisions win).
`pending_review` pairs are used only in rehearsal reports, labelled as such.

## Known limitations

- Guatemalan Gen Z slang is thinly documented online; GT has fewer terms and test pairs.
- Slang ages fast: a term bank dated today will sound old in a year. Models are tagged by data
  date (`genlingo-YYYY-MM`) so the talk can compare last month's David with this month's.
- Test references are one person's rewrite; chrF++ against a single reference underestimates
  valid alternative translations. Results are reported per origin and per direction.
"""
    (DATA / "DATASHEET.md").write_text(md, encoding="utf-8")
    print(f"DATASHEET.md: {len(pairs)} pairs, {len(terms)} terms")


if __name__ == "__main__":
    main()
