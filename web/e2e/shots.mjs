// Screenshots for design review: node e2e/shots.mjs [baseUrl] [outDir]
import { chromium, devices } from "@playwright/test";
const base = process.argv[2] ?? "http://localhost:3000";
const out = process.argv[3] ?? "e2e/shots";
const duel = process.env.DUEL_URL ?? "http://127.0.0.1:8787";
const browser = await chromium.launch();
const stage = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
await fetch(`${duel}/reset`, { method: "POST" });
await stage.goto(`${base}/presenter`);
await stage.waitForTimeout(1500);
await stage.screenshot({ path: `${out}/presenter-welcome.png` });
await stage.keyboard.press("e");
await stage.waitForTimeout(150);
await stage.screenshot({ path: `${out}/presenter-running.png` });
await stage.waitForTimeout(2000);
await stage.screenshot({ path: `${out}/presenter-evaluation.png` });
await stage.keyboard.press("/");
await stage.keyboard.type("no manches, la peli estuvo bien mid y me dio cringe");
await stage.keyboard.press("Enter");
await stage.waitForTimeout(2200);
await stage.screenshot({ path: `${out}/presenter-audience.png` });
const phone = await browser.newPage({ ...devices["Pixel 7"] });
await phone.goto(base);
await phone.waitForSelector("h1", { timeout: 20000 });
await phone.waitForTimeout(800);
await phone.screenshot({ path: `${out}/phone.png`, fullPage: true });
const admin = await browser.newPage({ viewport: { width: 1280, height: 800 } });
await admin.goto(`${base}/admin`);
await admin.waitForTimeout(2500);
await admin.screenshot({ path: `${out}/admin-signin.png` });
await browser.close();
console.log("ok");
